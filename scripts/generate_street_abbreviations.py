# Generates src/matchers/street_abbreviations.txt from the address
# dictionaries of libpostal (https://github.com/openvenues/libpostal),
# which are released under the MIT license.
#
# Usage, from the project root:
#
#   git clone --depth 1 https://github.com/openvenues/libpostal /tmp/libpostal
#   uv run scripts/generate_street_abbreviations.py /tmp/libpostal
#
# Only libpostal's text dictionaries are used, not its C library or
# its trained models.

import os
import subprocess
import sys

# Dictionaries whose entries are words of a street name. Each line is
# a canonical form, then its abbreviations and variants, separated by
# "|": "straße|str.|strasse".
WORD_FILES = [
    "street_types.txt",
    "directionals.txt",
    "personal_titles.txt",
    "qualifiers.txt",
]

# Suffixes that can be written as a separate word or joined to the
# word before: "Nussdorferplatz" and "Nussdorfer Platz".
SUFFIX_FILES = ["concatenated_suffixes_separable.txt"]

OUTPUT = "src/matchers/street_abbreviations.txt"


def main():
    libpostal = sys.argv[1]
    commit = subprocess.run(
        ["git", "-C", libpostal, "rev-parse", "HEAD"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()
    dictionaries = os.path.join(libpostal, "resources", "dictionaries")
    out = [
        "# DO NOT EDIT - THIS FILE IS GENERATED",
        "#",
        "# Generated by scripts/generate_street_abbreviations.py from the",
        f"# dictionaries of pkg:github/openvenues/libpostal@{commit}",
        "# Copyright (c) 2015 openvenues, released under the MIT license.",
        "#",
        "# Each line: kind (word or suffix), language, then the canonical",
        "# form and its variants, separated by |.",
    ]
    for lang in sorted(os.listdir(dictionaries)):
        lang_dir = os.path.join(dictionaries, lang)
        if not os.path.isdir(lang_dir):
            continue
        for kind, files in (("word", WORD_FILES), ("suffix", SUFFIX_FILES)):
            for name in files:
                path = os.path.join(lang_dir, name)
                if not os.path.exists(path):
                    continue
                with open(path, encoding="utf-8") as f:
                    for line in f:
                        line = line.split("#")[0].strip().lower()
                        if line and "\t" not in line:
                            out.append(f"{kind}\t{lang}\t{line}")
    with open(OUTPUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
